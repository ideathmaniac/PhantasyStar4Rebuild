/* See win/include/setjmp.h. Layout: rbx rbp rsi rdi r12 r13 r14 r15 rsp rip, then xmm6-xmm15. */
__asm__(
    ".text\n"
    ".globl ps4_setjmp\n"
    "ps4_setjmp:\n"
    "    movq %rbx, 0(%rcx)\n"
    "    movq %rbp, 8(%rcx)\n"
    "    movq %rsi, 16(%rcx)\n"
    "    movq %rdi, 24(%rcx)\n"
    "    movq %r12, 32(%rcx)\n"
    "    movq %r13, 40(%rcx)\n"
    "    movq %r14, 48(%rcx)\n"
    "    movq %r15, 56(%rcx)\n"
    "    leaq 8(%rsp), %rdx\n"          /* rsp as after our return */
    "    movq %rdx, 64(%rcx)\n"
    "    movq (%rsp), %rdx\n"           /* return address */
    "    movq %rdx, 72(%rcx)\n"
    "    movdqu %xmm6, 80(%rcx)\n"
    "    movdqu %xmm7, 96(%rcx)\n"
    "    movdqu %xmm8, 112(%rcx)\n"
    "    movdqu %xmm9, 128(%rcx)\n"
    "    movdqu %xmm10, 144(%rcx)\n"
    "    movdqu %xmm11, 160(%rcx)\n"
    "    movdqu %xmm12, 176(%rcx)\n"
    "    movdqu %xmm13, 192(%rcx)\n"
    "    movdqu %xmm14, 208(%rcx)\n"
    "    movdqu %xmm15, 224(%rcx)\n"
    "    xorl %eax, %eax\n"
    "    ret\n"
    ".globl ps4_longjmp\n"
    "ps4_longjmp:\n"
    "    movl %edx, %eax\n"
    "    testl %eax, %eax\n"
    "    jnz 1f\n"
    "    movl $1, %eax\n"
    "1:\n"
    "    movq 0(%rcx), %rbx\n"
    "    movq 8(%rcx), %rbp\n"
    "    movq 16(%rcx), %rsi\n"
    "    movq 24(%rcx), %rdi\n"
    "    movq 32(%rcx), %r12\n"
    "    movq 40(%rcx), %r13\n"
    "    movq 48(%rcx), %r14\n"
    "    movq 56(%rcx), %r15\n"
    "    movdqu 80(%rcx), %xmm6\n"
    "    movdqu 96(%rcx), %xmm7\n"
    "    movdqu 112(%rcx), %xmm8\n"
    "    movdqu 128(%rcx), %xmm9\n"
    "    movdqu 144(%rcx), %xmm10\n"
    "    movdqu 160(%rcx), %xmm11\n"
    "    movdqu 176(%rcx), %xmm12\n"
    "    movdqu 192(%rcx), %xmm13\n"
    "    movdqu 208(%rcx), %xmm14\n"
    "    movdqu 224(%rcx), %xmm15\n"
    "    movq 64(%rcx), %rsp\n"
    "    jmpq *72(%rcx)\n"
);
